def _load_rating_set(path):
    items = [json.loads(l) for l in open(path, encoding="utf-8")]
    h = [it["text"] for it in items if it["id"].startswith("H_")]
    g = [it["text"] for it in items if it["id"].startswith(("G_", "GZ_"))]
    return h, g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None, help="配置文件（可用 configs/default_macbert.yaml 切换 MacBERT）")
    args = ap.parse_args()
    cfg = load_config(args.config) if args.config else Config()
    ev = Evaluator(cfg)

    data_path = "data/eval_dataset/rating_set.jsonl"
    print("加载评分集（短文叙事分布 H/G）...", flush=True)
    h_all, g_all = _load_rating_set(data_path)
    print(f"  H={len(h_all)}  G={len(g_all)}", flush=True)

    print("拟合完整评估器（三视图）...", flush=True)
    ev.fit(h_all, g_all)

    groups = {
        "1.像人且高质(人类叙事)": like_high_quality(),
        "2.像人但低质(空洞废话)": like_low_quality(),
        "3.不像人且低质(机器文本)": unlike_low_quality(),
        "4.不像人但高质(独特风格)": unlike_high_quality(),
    }

    lam = ev.scorer.lambdas

    def like3(text):
        c = ev.scorer.components(text)
        return (c["S_disc"], c["S_repr"], c["S_attr"],
                float(np.clip(lam[0] * c["S_disc"] + lam[1] * c["S_repr"] + lam[2] * c["S_attr"], 0.0, 1.0)))

    print("\n=== 像人分(三视图) 与 质量 的解耦验证 ===")
    print(f"{'样本组':<24}{'S_disc':>8}{'S_repr':>8}{'S_attr':>8}{'像人分':>9}")
    results = {}
    for name, texts in groups.items():
        comps = [like3(t) for t in texts]
        results[name] = [c[3] for c in comps]
        print(f"{name:<24}"
              f"{np.mean([c[0] for c in comps]):>8.3f}"
              f"{np.mean([c[1] for c in comps]):>8.3f}"
              f"{np.mean([c[2] for c in comps]):>8.3f}"
              f"{np.mean([c[3] for c in comps]):>9.3f}")

    print("\n=== 解耦检验 ===")
    like_hi = np.mean(results["1.像人且高质(人类叙事)"])
    like_lo = np.mean(results["2.像人但低质(空洞废话)"])
    un_like_lo = np.mean(results["3.不像人且低质(机器文本)"])
    un_like_hi = np.mean(results["4.不像人但高质(独特风格)"])

    print(f"  像人分应高的两组(1,2): {like_hi:.3f}, {like_lo:.3f}")
    print(f"  像人分应低的两组(3,4): {un_like_lo:.3f}, {un_like_hi:.3f}")
    ok_like = (like_hi > un_like_hi) and (like_lo > un_like_lo)
    print(f"  像人分按'像不像人'而非'质量'区分: {'[通过]' if ok_like else '[失败]'}")
    sep_by_quality = abs(like_hi - like_lo)
    sep_by_like = abs(like_hi - un_like_hi)
    print(f"  像人分组间差异（质量维度）={sep_by_quality:.3f} vs （像人维度）={sep_by_like:.3f}")
    ok_sep = sep_by_quality < sep_by_like
    print(f"  质量维度差异 < 像人维度差异（解耦）: {'[通过]' if ok_sep else '[失败]'}")

    print("\n=== 单篇像人分明细 ===")
    for name, scores in results.items():
        print(f"  {name}: " + "  ".join(f"{s:.3f}" for s in scores))


if __name__ == "__main__":
    main()
